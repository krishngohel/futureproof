export const MacbookScroll = ({
  src,
  screenContent,
  showGradient,
  title,
  badge,
}: {
  src?: string;
  screenContent?: React.ReactNode;
  showGradient?: boolean;
  title?: string | React.ReactNode;
  badge?: React.ReactNode;
}) => {
  const ref = useRef<HTMLDivElement>(null);
  const { scrollYProgress } = useScroll({
    target: ref,
    offset: ["start start", "end start"],
  });

  // Viewport-responsive scale: stays at 1× up to 1440px (where it already
  // looked perfect), then grows gently — +0.25× per 480px — up to 1.5×.
  const [vwScale, setVwScale] = useState(1);
  useEffect(() => {
    const update = () => {
      const vw = window.innerWidth;
      if (vw < 640) {
        setVwScale(0.35);
      } else if (vw < 768) {
        setVwScale(0.5);
      } else {
        // 1× at ≤1440px, linear growth above that, capped at 1.5×
        const extra = Math.max(0, (vw - 1440) / 480) * 0.25;
        setVwScale(Math.min(1.0 + extra, 1.5));
      }
    };
    update();
    window.addEventListener("resize", update);
    return () => window.removeEventListener("resize", update);
  }, []);

  // Drive all transforms directly from scroll position — no springs.
  // Springs are designed for gesture/state animations; for scroll-scrubbing
  // they lag behind the real scroll position and read as choppiness.
  const scaleX        = useTransform(scrollYProgress, [0, 0.16],  [1.2, 1.0]);
  const scaleY        = useTransform(scrollYProgress, [0, 0.16],  [0.6, 1.0]);
  const rotate        = useTransform(scrollYProgress, [0.03, 0.16], [-28, 0]);
  // Lid travel stays at 350px (unscaled space) — the body is ~352px tall, so
  // this correctly closes the lid onto the body regardless of outer vwScale.
  const translate     = useTransform(scrollYProgress, [0.16, 0.52], [0, 350]);
  const bodyScale     = useTransform(scrollYProgress, [0.16, 0.52], [1.0, 1.45]);
  const textTransform = useTransform(scrollYProgress, [0, 0.16],  [0, 100]);
  const textOpacity   = useTransform(scrollYProgress, [0, 0.1],   [1, 0]);

  return (
    <div
      ref={ref}
      className="flex min-h-[140vh] shrink-0 transform flex-col items-center justify-start py-0 [perspective:800px] md:pt-[194px] md:pb-48"
      style={{ transform: `scale(${vwScale})`, transformOrigin: "top center" }}
    >
      <motion.h2
        style={{ translateY: textTransform, opacity: textOpacity, willChange: "transform, opacity" }}
        className="mb-20 text-center text-3xl font-bold text-white"
      >
        {title || (
          <span>
            Your AI learning platform. <br /> Built to take you further.
          </span>
        )}
      </motion.h2>
      <motion.div style={{ scale: bodyScale, transformOrigin: "top center", willChange: "transform" }}>
      <Lid
        src={src}
        screenContent={screenContent}
        scaleX={scaleX}
        scaleY={scaleY}
        rotate={rotate}
        translate={translate}
      />
      <div className="relative -z-10 h-[22rem] w-[32rem] overflow-hidden rounded-2xl bg-[#272729]">
        <div className="relative h-10 w-full">
          <div className="absolute inset-x-0 mx-auto h-4 w-[80%] bg-[#050505]" />
        </div>
        <div className="relative flex">
          <div className="mx-auto h-full w-[10%] overflow-hidden">
            <SpeakerGrid />
          </div>
          <div className="mx-auto h-full w-[80%]">
            <Keypad />
          </div>
          <div className="mx-auto h-full w-[10%] overflow-hidden">
            <SpeakerGrid />
          </div>
        </div>
        <Trackpad />
        <div className="absolute inset-x-0 bottom-0 mx-auto h-2 w-20 rounded-tl-3xl rounded-tr-3xl bg-gradient-to-t from-[#272729] to-[#050505]" />
        {showGradient && (
          <div className="absolute inset-x-0 bottom-0 z-50 h-40 w-full bg-gradient-to-t from-black via-black to-transparent" />
        )}
        {badge && <div className="absolute bottom-4 left-4">{badge}</div>}
      </div>
      </motion.div>
    </div>
  );
};

